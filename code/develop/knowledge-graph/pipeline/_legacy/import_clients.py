PROVINCE = "湖北省"

def create_client_node(tx, name, phone, address, level, county, city, source="测绘公司名录"):
    """创建 Client 节点"""
    query = """
    MERGE (c:Client {name: $name})
    SET c.phone = $phone,
        c.address = $address,
        c.level = $level,
        c.county = $county,
        c.city = $city,
        c.province = $province,
        c.source = $source,
        c.updated_at = datetime()
    RETURN c.name AS name
    """
    result = tx.run(query, name=name, phone=phone, address=address,
                    level=level, county=county, city=city,
                    province=PROVINCE, source=source)
    return result.single()["name"]

def ensure_location(tx, name, loc_type, parent_name=None):
    """确保 Location 节点存在"""
    if not name or name == "":
        return None
    
    query = """
    MERGE (l:Location {name: $name})
    SET l.type = $loc_type,
        l.province = $province
    RETURN l.name AS name
    """
    result = tx.run(query, name=name, loc_type=loc_type, province=PROVINCE)
    return result.single()["name"]

def create_relation(tx, from_name, to_name, rel_type, props=None):
    """创建关系"""
    if not from_name or not to_name:
        return
    rel_clause = f"MERGE (a)-[:{rel_type}]->(b)"
    query = f"""
    MATCH (a {{name: $from_name}})
    MATCH (b {{name: $to_name}})
    {rel_clause}
    """
    tx.run(query, from_name=from_name, to_name=to_name)

def run():
    with driver.session() as session:
        # 1. 确保湖北省 Location 存在
        session.execute_write(ensure_location, PROVINCE, "province")
        
        count = {"clients": 0, "counties": 0, "cities": 0, "relations": 0}
        
        for city, counties in CLIENTS_DATA.items():
            # 2. 创建城市 Location
            session.execute_write(ensure_location, city, "city", PROVINCE)
            count["cities"] += 1
            
            # 3. 城市 → 湖北省
            session.execute_write(create_relation, city, PROVINCE, "BELONGS_TO")
            count["relations"] += 1
            
            for county, companies in counties.items():
                # 4. 创建区县 Location
                session.execute_write(ensure_location, county, "county", city)
                count["counties"] += 1
                
                # 5. 区县 → 城市
                session.execute_write(create_relation, county, city, "BELONGS_TO")
                count["relations"] += 1
                
                # 6. 创建各公司 Client 节点
                for company in companies:
                    name, phone, address, level = company
                    session.execute_write(create_client_node, 
                        name, phone, address, level, county, city)
                    count["clients"] += 1
                    
                    # 7. Client → 区县
                    session.execute_write(create_relation, name, county, "LOCATED_IN")
                    count["relations"] += 1
        
        print(f"✅ 导入完成")
        print(f"  Client 公司: {count['clients']}")
        print(f"  Location 区县: {count['counties']}")
        print(f"  Location 城市: {count['cities']}")
        print(f"  关系: {count['relations']}")
    
    driver.close()

if __name__ == "__main__":
    run()
